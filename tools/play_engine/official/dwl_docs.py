def row_values(s, kind):
    n = s["runs"]
    v = dict(s)
    v["winp"] = 100.0 * s["wins"] / n if n else None
    loss = s.get("loss") or collections.Counter()
    tl = sum(c for k, c in loss.items() if k and ("agenda" in k or "time" in k or "clock" in k or "unfinished" in k))
    dl = sum(c for k, c in loss.items() if k and ("defeated" in k or "resigned" in k))
    v["loss_time"] = 100.0 * tl / n if n else None
    v["loss_def"] = 100.0 * dl / n if n else None
    return v


